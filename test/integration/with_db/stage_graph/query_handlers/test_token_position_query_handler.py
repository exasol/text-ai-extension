_word_pattern = re.compile(r"\w+", re.MULTILINE)


class TokenType(Enum):
    """
    We will use two types of tokens - distinct words and character n-grams
    of certain length.
    """

    WORD = auto()
    N_GRAM = auto()


@dataclass
class TokenizerType:
    token_type: TokenType
    length: int = 0  # only for n-grams


def _get_word_count(start_pos: int, end_pos):
    return len(_word_pattern.findall(_DOCUMENT, pos=start_pos, endpos=end_pos))


def _token_iterator(tz_type: TokenizerType) -> Generator[tuple[int, int], None, None]:
    """
    Iterates over the tokens, yielding the token's character span.
    """
    if tz_type.token_type == TokenType.WORD:
        for match in _word_pattern.finditer(_DOCUMENT):
            yield match.start(), match.end()
    else:
        for i in range(0, len(_DOCUMENT), tz_type.length):
            yield i, i + tz_type.length


def _token_span(
    start_pos: int, end_pos: int, tz_type: TokenizerType
) -> tuple[int | None, int | None]:
    """
    For the provided character span returns the token span, such that all tokens
    in the span are contained by the character span.
    """
    if tz_type.token_type == TokenType.WORD:
        start_token = _get_word_count(0, start_pos)
        end_token = start_token + _get_word_count(start_pos, end_pos)
    else:
        start_token = (start_pos + tz_type.length - 1) // tz_type.length
        end_token = end_pos // tz_type.length
    if end_token <= start_token:
        return None, None
    return start_token, end_token


