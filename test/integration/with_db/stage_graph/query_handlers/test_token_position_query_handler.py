def _delete_table(table: TableLikeName, pyexasol_connection: ExaConnection) -> None:
    query = f"DROP TABLE IF EXISTS {table.fully_qualified}"
    pyexasol_connection.execute(query)


def _create_table(
    table: TableLikeName, content: pd.DataFrame, pyexasol_connection: ExaConnection
) -> None:
    def column_def(col_name, col_dtype) -> str:
        if is_integer_dtype(col_dtype):
            sql_type = "INTEGER"
        elif is_string_dtype(col_dtype):
            sql_type = "VARCHAR(2000000)"
        else:
            raise ValueError(f"Unsupported type {col_dtype}")
        return f'"{col_name}" {sql_type}'

    columns = ", ".join(
        column_def(c, dt) for c, dt in zip(content.columns, content.dtypes)
    )
    query = f"CREATE OR REPLACE TABLE {table.fully_qualified}({columns})"
    pyexasol_connection.execute(query)


def _populate_table(
    table: TableLikeName, content: pd.DataFrame, pyexasol_connection: ExaConnection
):
    def cell_value(cell, dtype) -> str:
        if cell is None:
            return "NULL"
        if is_string_dtype(dtype):
            return sql_text_value(cell)
        return str(cell)

    def row_values(row: pd.Series) -> str:
        return ", ".join(
            cell_value(cell, dtype) for cell, dtype in zip(row, content.dtypes)
        )

    values = ", ".join(f"({row_values(row)})" for _, row in content.iterrows())
    query = f"INSERT INTO {table.fully_qualified} VALUES {values}"
    pyexasol_connection.execute(query)


