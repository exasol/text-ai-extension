def test_query_handler(
    setup_database,
    pyexasol_connection,
    setup_token_position_test,
    query_handler_runner_factory,
    entity_output,
    expected_position_df,
    token_span,
    token_view,
):
    """
    The test creates the token position view, selects all rows from it and compares
    them with the expected content.

    The test doesn't cover the algorithms. Instead, the outputs of the stages pretending
    to be an algorithm and a tokenizer are stored in tables by the fixtures beforehand.
    The `expected_position_df` fixture provides the expected content of the view,
    calculated for a given type of the tokenizer.

    The test runs for several different tokenizers. This is defined by the parameterized
    fixture `tokenizer_type`. The following cases are covered.
    - The tokens are aligned with extracted entities.
    - No token alignment - the entities start and/or end in a middle of a token.
    - Some of the entities do not cover entirely any single token.
    - None of the entities cover a token entirely.
    """
    query_handler_runner = query_handler_runner_factory()
    query_handler_runner.run()

    outputs = cast(_EntityOutput, entity_output.columns)
    order = ",".join(
        c.quoted_name
        for c in [
            outputs.text_span.doc_id,
            outputs.text_span.begin,
            outputs.entity_span.begin,
        ]
    )
    query = f"SELECT * FROM {token_view.fully_qualified} ORDER BY {order}"
    position_df = pyexasol_connection.export_to_pandas(query)
    # The tokenizer version is a hash and cannot be predicted reliably, so let's not look at it
    _, tok_ver, _, _ = token_span
    position_df.drop(columns=[tok_ver], inplace=True)
    matcher = DataFrameMatcher(position_df, expected_position_df)
    assert matcher, matcher.diff()
